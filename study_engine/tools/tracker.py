#!/usr/bin/env python3
"""
Mentor progress tracker — weak areas, spaced revision, priorities.

Run from repo root:
  python3 study_engine/tools/tracker.py dashboard                  # rebuild study_engine/PROGRESS.md
  python3 study_engine/tools/tracker.py due                        # revisions due today (do first!)
  python3 study_engine/tools/tracker.py next [N]                   # top-N units by priority (DECISION_ENGINE §2)
  python3 study_engine/tools/tracker.py exam DBMS 2026-12-02       # set exam date
  python3 study_engine/tools/tracker.py status DBMS 4 learning     # not_started|learning|learned|mastered
  python3 study_engine/tools/tracker.py log DBMS 4 14 20 --type test --weak "joins;correlated subquery"
  python3 study_engine/tools/tracker.py conf DBMS 4 3              # self-rated confidence 0-5
  python3 study_engine/tools/tracker.py addsubject OS "Operating Systems"   # new subject
  python3 study_engine/tools/tracker.py addunit OS 1 "Introduction" 15      # unit with weightage %
"""
import json, sys, os, argparse, datetime as dt

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB = os.path.join(ROOT, "progress.json")
MD = os.path.join(ROOT, "PROGRESS.md")
TODAY = dt.date.today()


def load():
    with open(DB, encoding="utf-8") as f:
        return json.load(f)


def save(d):
    with open(DB, "w", encoding="utf-8") as f:
        json.dump(d, f, indent=2, ensure_ascii=False)


def days_left(subj):
    e = subj.get("exam_date")
    if not e:
        return None
    return (dt.date.fromisoformat(e) - TODAY).days


def intervals(dleft):
    return [1, 2, 4] if (dleft is not None and dleft < 10) else [1, 3, 7, 14]


def last_pct(u):
    if not u["scores"]:
        return None
    s = u["scores"][-1]
    return 100.0 * s["score"] / s["max"]


def band(p):
    if p is None:
        return "—"
    return "STRONG" if p >= 80 else "SHAKY" if p >= 60 else "WEAK"


def priority(subj, u):
    dl = days_left(subj)
    urg = 1 if dl is None else 5 if dl <= 3 else 4 if dl <= 7 else 3 if dl <= 14 else 2 if dl <= 21 else 1
    w = (u.get("weight") or 15) / 5
    weak = 5 - u.get("confidence", 0)
    freq = min(u.get("frequency", 1), 5)
    p = last_pct(u)
    mast = 0 if p is None else 5 if p >= 80 else 3 if p >= 60 else 0
    return round(3 * urg + 2 * w + 2 * weak + freq - mast, 1)


def cmd_dashboard(d, _):
    L = ["# 📊 PROGRESS DASHBOARD", f"_Auto-generated by tracker.py on {TODAY}. Do not edit by hand._", ""]
    L += ["| Subject | Exam date | Days left | Units learned | Avg last score | Weak units |",
          "|---|---|---|---|---|---|"]
    for code, s in d["subjects"].items():
        us = s["units"].values()
        learned = sum(u["status"] in ("learned", "mastered") for u in us)
        ps = [last_pct(u) for u in us if last_pct(u) is not None]
        weak = [k for k, u in s["units"].items() if band(last_pct(u)) == "WEAK"]
        dl = days_left(s)
        L.append(f"| **{code}** {s['name']} | {s.get('exam_date') or '❓ ask'} | {'' if dl is None else dl} | "
                 f"{learned}/{len(s['units'])} | {f'{sum(ps)/len(ps):.0f} %' if ps else '—'} | {', '.join('U'+w for w in weak) or '—'} |")
    L += ["", "## 🔁 Due revisions", ""]
    due = list(iter_due(d))
    L += [f"- {c} U{k} {u['title']} (due {u['next_revision']})" for c, k, u in due] or ["- nothing due 🎉"]
    L += ["", "## 🎯 Next best units (priority score)", ""]
    L += [f"{i}. {c} U{k} — {u['title']}  (score {p})" for i, (p, c, k, u) in enumerate(ranked(d)[:8], 1)]
    for code, s in d["subjects"].items():
        L += ["", f"## {code} — {s['name']}", "", "| Unit | Title | Wt % | Status | Conf | Last | Band | Next rev | Weak topics |",
              "|---|---|---|---|---|---|---|---|---|"]
        for k, u in s["units"].items():
            p = last_pct(u)
            L.append(f"| {k} | {u['title']} | {u.get('weight') or '?'} | {u['status']} | {u.get('confidence',0)} | "
                     f"{'' if p is None else f'{p:.0f}%'} | {band(p)} | {u.get('next_revision') or ''} | {'; '.join(u.get('weak_topics', []))} |")
    if d.get("sessions"):
        L += ["", "## 📝 Recent activity", ""] + [f"- {x}" for x in d["sessions"][-10:]]
    open(MD, "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("wrote", MD)


def iter_due(d):
    for code, s in d["subjects"].items():
        for k, u in s["units"].items():
            nr = u.get("next_revision")
            if nr and dt.date.fromisoformat(nr) <= TODAY:
                yield code, k, u


def ranked(d):
    out = []
    for code, s in d["subjects"].items():
        for k, u in s["units"].items():
            if u["status"] != "mastered":
                out.append((priority(s, u), code, k, u))
    return sorted(out, key=lambda x: -x[0])


def cmd_due(d, a):
    due = list(iter_due(d))
    if not due:
        print("Nothing due today.")
    for c, k, u in due:
        print(f"{c} U{k} {u['title']}  (due {u['next_revision']}, band {band(last_pct(u))}, weak: {'; '.join(u.get('weak_topics', [])) or '-'})")


def cmd_next(d, a):
    for p, c, k, u in ranked(d)[: a.n]:
        print(f"{p:5}  {c} U{k} {u['title']}  [{u['status']}]")


def unit(d, a):
    return d["subjects"][a.subject]["units"][str(a.unit)]


def cmd_log(d, a):
    s = d["subjects"][a.subject]; u = unit(d, a)
    pct = 100 * a.score / a.max
    u["scores"].append({"date": str(TODAY), "type": a.type, "score": a.score, "max": a.max})
    if a.weak:
        for t in [x.strip() for x in a.weak.split(";") if x.strip()]:
            if t not in u["weak_topics"]:
                u["weak_topics"].append(t)
    if a.fixed:
        u["weak_topics"] = [t for t in u["weak_topics"] if t not in [x.strip() for x in a.fixed.split(";")]]
    iv = intervals(days_left(s))
    step = u.get("rev_step", 0)
    if pct >= 80:
        step = min(step + 1, len(iv) - 1)
        if step == len(iv) - 1 and len([x for x in u["scores"] if 100 * x["score"] / x["max"] >= 80]) >= 3:
            u["status"] = "mastered"
    elif pct < 60:
        step = 0
    u["rev_step"] = step
    u["next_revision"] = str(TODAY + dt.timedelta(days=iv[step]))
    if u["status"] in ("not_started", "learning"):
        u["status"] = "learned"
    u["confidence"] = max(0, min(5, round(pct / 20)))
    d.setdefault("sessions", []).append(f"{TODAY}: {a.subject} U{a.unit} {a.type} {a.score}/{a.max} ({pct:.0f}%, {band(pct)})")
    save(d); print(f"logged {pct:.0f}% → {band(pct)}; next revision {u['next_revision']}")
    cmd_dashboard(d, a)


def cmd_status(d, a):
    u = unit(d, a); u["status"] = a.status
    if a.status == "learned" and not u.get("next_revision"):
        u["next_revision"] = str(TODAY + dt.timedelta(days=1))
    save(d); cmd_dashboard(d, a)


def cmd_conf(d, a):
    unit(d, a)["confidence"] = a.value; save(d); cmd_dashboard(d, a)


def cmd_exam(d, a):
    d["subjects"][a.subject]["exam_date"] = a.date; save(d); cmd_dashboard(d, a)


def cmd_addsubject(d, a):
    d["subjects"].setdefault(a.subject, {"name": a.name, "exam_date": None, "units": {}}); save(d); print("added")


def cmd_addunit(d, a):
    d["subjects"][a.subject]["units"][str(a.unit)] = new_unit(a.title, a.weight); save(d); print("added")


def new_unit(title, weight=None, freq=1):
    return {"title": title, "weight": weight, "status": "not_started", "confidence": 0, "frequency": freq,
            "scores": [], "weak_topics": [], "next_revision": None, "rev_step": 0}


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    sp.add_parser("dashboard"); sp.add_parser("due")
    p = sp.add_parser("next"); p.add_argument("n", nargs="?", type=int, default=5)
    p = sp.add_parser("log"); p.add_argument("subject"); p.add_argument("unit"); p.add_argument("score", type=float)
    p.add_argument("max", type=float); p.add_argument("--type", default="test"); p.add_argument("--weak"); p.add_argument("--fixed")
    p = sp.add_parser("status"); p.add_argument("subject"); p.add_argument("unit")
    p.add_argument("status", choices=["not_started", "learning", "learned", "mastered"])
    p = sp.add_parser("conf"); p.add_argument("subject"); p.add_argument("unit"); p.add_argument("value", type=int)
    p = sp.add_parser("exam"); p.add_argument("subject"); p.add_argument("date")
    p = sp.add_parser("addsubject"); p.add_argument("subject"); p.add_argument("name")
    p = sp.add_parser("addunit"); p.add_argument("subject"); p.add_argument("unit"); p.add_argument("title"); p.add_argument("weight", nargs="?", type=float)
    a = ap.parse_args()
    d = load()
    globals()["cmd_" + a.cmd](d, a)


if __name__ == "__main__":
    main()
